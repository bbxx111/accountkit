// purgedUserDDL applies only the separately authorized purged_user table to a historical
// test schema, so catalog comparisons still detect anything else.
const purgedUserDDL = `CREATE TABLE purged_user (
 user_id TEXT COLLATE "C" PRIMARY KEY CONSTRAINT purged_user_user_id_format CHECK (user_id ~ '^u_[0-9a-hjkmnp-tv-z]{13}$'),
 seq BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY CONSTRAINT uk_purged_user_seq UNIQUE,
 purge_time TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX idx_purged_user_purge_time ON purged_user(purge_time)`

// Pin the published v0.6.0 definition exactly (the tag commit). Never derive it from today's SQL.
const publishedV060Commit = "ec6802cd221db3ce107e79bac92174bc35a0ba7d"

func publishedV060Initial(t *testing.T) (*pgx.ConnConfig, string, *pgx.Conn) {
	t.Helper()
	initial, err := exec.Command("git", "show", publishedV060Commit+":migrations/0001_init.up.sql").Output()
	if err != nil {
		t.Fatal(err)
	}
	cfg, schema := safetyDB(t)
	c := migrationTestConn(t, cfg, schema)
	for _, q := range []string{"CREATE SCHEMA " + schema, string(initial), "CREATE TABLE schema_migrations(version bigint PRIMARY KEY,dirty boolean NOT NULL); INSERT INTO schema_migrations VALUES(1,false)"} {
		if _, err := c.Exec(context.Background(), q); err != nil {
			t.Fatal(err)
		}
	}
	return cfg, schema, c
}

func TestPurgedUserInitialDefinition(t *testing.T) {
	cfg, schema, c := consolidatedProfileAttributesInitial(t)
	ctx := context.Background()
	assertVersion(t, cfg, schema, 1, false)
	var identity, generated string
	if err := c.QueryRow(ctx, `SELECT is_identity, identity_generation FROM information_schema.columns WHERE table_schema=$1 AND table_name='purged_user' AND column_name='seq'`, schema).Scan(&identity, &generated); err != nil {
		t.Fatal(err)
	}
	if identity != "YES" || generated != "ALWAYS" {
		t.Fatalf("seq identity = %s %s", identity, generated)
	}
	if _, err := c.Exec(ctx, `INSERT INTO purged_user(user_id) VALUES('u_0000000000001'),('u_0000000000002')`); err != nil {
		t.Fatal(err)
	}
	var first, second int64
	if err := c.QueryRow(ctx, `SELECT min(seq), max(seq) FROM purged_user`).Scan(&first, &second); err != nil || second <= first {
		t.Fatalf("seq not increasing: %d %d %v", first, second, err)
	}
	for name, q := range map[string]string{
		"duplicate user":  `INSERT INTO purged_user(user_id) VALUES('u_0000000000001')`,
		"bad user id":     `INSERT INTO purged_user(user_id) VALUES('users/1')`,
		"explicit seq":    `INSERT INTO purged_user(user_id, seq) VALUES('u_0000000000003', 1)`,
		"null purge time": `INSERT INTO purged_user(user_id, purge_time) VALUES('u_0000000000004', NULL)`,
	} {
		if _, err := c.Exec(ctx, q); err == nil {
			t.Errorf("%s: expected constraint violation", name)
		}
	}
	// 新安装与“v0.6.0 + 仅授权 DDL”的目录完全一致，证明 0001 只新增了 purged_user。
	_, oldSchema, old := publishedV060Initial(t)
	if _, err := old.Exec(ctx, purgedUserDDL); err != nil {
		t.Fatal(err)
	}
	_, freshSchema, fresh := consolidatedProfileAttributesInitial(t)
	if want, got := migrationCatalog(t, old, oldSchema), migrationCatalog(t, fresh, freshSchema); want != got {
		t.Fatalf("current initial differs from v0.6.0 plus purged_user\nwant: %s\ngot: %s", want, got)
	}
	// 重复 Up 不改变已安装结构。
	catalog := migrationCatalog(t, c, schema)
	if err := Up(ctx, cfg, schema); err != nil || catalog != migrationCatalog(t, c, schema) {
		t.Fatalf("repeat Up: %v", err)
	}
}

func TestPurgedUserMissingV060Rejected(t *testing.T) {
	cfg, schema, c := publishedV060Initial(t)
	seedRenameFlow(t, c, "sign_in_completion_flow")
	assertPurgedUserRejected(t, cfg, schema, c, 2)
}

// Positive control: v0.6.0 plus only the authorized table is accepted, proving the
// rejection above comes from the purged_user check alone.
func TestPurgedUserV060WithTableAccepted(t *testing.T) {
	cfg, schema, c := publishedV060Initial(t)
	ctx := context.Background()
	if _, err := c.Exec(ctx, purgedUserDDL); err != nil {
		t.Fatal(err)
	}
	seedRenameFlow(t, c, "sign_in_completion_flow")
	catalog, data := migrationCatalog(t, c, schema), renameDataSnapshot(t, c, "sign_in_completion_flow")
	if err := Up(ctx, cfg, schema); err != nil {
		t.Fatal(err)
	}
	assertVersion(t, cfg, schema, 1, false)
	if catalog != migrationCatalog(t, c, schema) || data != renameDataSnapshot(t, c, "sign_in_completion_flow") {
		t.Fatal("accepted baseline was mutated")
	}
}

func TestPurgedUserDriftRejected(t *testing.T) {
	for _, ddl := range []string{
		`ALTER TABLE purged_user DROP CONSTRAINT uk_purged_user_seq`,
		`ALTER TABLE purged_user ALTER COLUMN seq DROP IDENTITY`,
		`ALTER TABLE purged_user ALTER COLUMN seq SET GENERATED BY DEFAULT`,
		`ALTER TABLE purged_user DROP CONSTRAINT purged_user_user_id_format`,
		`ALTER TABLE purged_user ALTER COLUMN purge_time DROP NOT NULL`,
		`ALTER TABLE purged_user ALTER COLUMN user_id TYPE varchar(32)`,
		`DROP INDEX idx_purged_user_purge_time`,
		`ALTER TABLE purged_user ADD COLUMN extra text`,
		// 序号选项漂移会破坏“序号顺序 = 提交顺序”。
		`ALTER TABLE purged_user ALTER COLUMN seq SET CACHE 10`,
		`ALTER TABLE purged_user ALTER COLUMN seq SET INCREMENT BY 2`,
		`ALTER TABLE purged_user ALTER COLUMN seq SET CYCLE`,
	} {
		t.Run(ddl, func(t *testing.T) {
			cfg, schema, c := consolidatedProfileAttributesInitial(t)
			seedRenameFlow(t, c, "sign_in_completion_flow")
			if _, err := c.Exec(context.Background(), ddl); err != nil {
				t.Fatal(err)
			}
			assertPurgedUserRejected(t, cfg, schema, c, 1)
		})
	}
}

func assertPurgedUserRejected(t *testing.T, cfg *pgx.ConnConfig, schema string, c *pgx.Conn, attempts int) {
	t.Helper()
	ctx := context.Background()
	catalog, data := migrationCatalog(t, c, schema), renameDataSnapshot(t, c, "sign_in_completion_flow")
	for range attempts {
		if err := Up(ctx, cfg, schema); !errors.Is(err, ErrIncompatibleBaseline) || !strings.Contains(err.Error(), "purged_user") {
			t.Fatal("incompatible purged_user accepted, rejected by another check, or lock leaked:", err)
		}
	}
	assertVersion(t, cfg, schema, 1, false)
	if catalog != migrationCatalog(t, c, schema) || data != renameDataSnapshot(t, c, "sign_in_completion_flow") {
		t.Fatal("rejection mutated database")
	}
	if _, err := c.Exec(ctx, "UPDATE schema_migrations SET dirty=true"); err != nil {
		t.Fatal(err)
	}
	var dirty migrate.ErrDirty
	if err := Up(ctx, cfg, schema); !errors.As(err, &dirty) || dirty.Version != 1 {
		t.Fatal("dirty precedence", err)
	}
	assertVersion(t, cfg, schema, 1, true)
	if catalog != migrationCatalog(t, c, schema) || data != renameDataSnapshot(t, c, "sign_in_completion_flow") {
		t.Fatal("dirty rejection mutated database")
	}
}
